import {test,expect} from '@playwright/test'
test('ensayo térmico no produce compatibilidad usando relieve',async({page})=>{
 await page.goto('/#personalizado')
 const dialog=page.locator('dialog[open]')
 await dialog.getByLabel('¿Qué querés estudiar o ensayar?').selectOption('thermal')
 const criteria=dialog.getByRole('region',{name:'Criterios del ensayo'})
 await expect(criteria).toContainText('Ciclos de temperatura superficial')
 await expect(criteria).toContainText('Iluminación y sombra')
 const button=dialog.getByRole('button',{name:'Comparar solo el contexto topográfico',exact:true})
 await expect(button).toBeDisabled()
 await dialog.getByLabel('Comparar solo el contexto topográfico; no evaluar la compatibilidad de este ensayo.').check()
 await expect(button).toBeEnabled()
 await dialog.getByLabel('Cobertura de búsqueda').selectOption('catalogue')
 await button.click()
 await expect(dialog).toBeHidden({timeout:30000})
 await expect(page.getByRole('region',{name:'Objetivo de la comparación'})).toContainText('Compatibilidad del ensayo pendiente')
 await page.getByRole('region',{name:'Candidatos de la ejecución'}).getByRole('listitem').first().getByRole('button').click()
 await expect(page.getByRole('region',{name:'Evidencia del candidato'})).toContainText('Falta: Ciclos de temperatura superficial')
 await page.getByRole('button',{name:'Editar análisis',exact:true}).click()
 await dialog.getByLabel('¿Qué querés estudiar o ensayar?').selectOption('excavation')
 await expect(criteria).toContainText('Granulometría y abrasividad')
 await expect(button).toBeDisabled()
})
