import {test,expect} from '@playwright/test'
test('MODIS real aparece en el candidato terrestre con fecha y límites',async({page})=>{
 await page.route('https://**/*',route=>route.abort())
 await page.goto('/#personalizado')
 const dialog=page.locator('dialog[open]')
 await dialog.getByLabel('1 · Destino de misión').selectOption('luna-mons-mouton')
 await dialog.getByLabel('2 · Cobertura de búsqueda').selectOption('pilot')
 await dialog.getByRole('button',{name:'Buscar análogos topográficos',exact:true}).click()
 await expect(dialog.getByRole('region',{name:'Resultados científicos'})).toBeVisible({timeout:30000})
 await dialog.getByRole('button',{name:'Ver recorte exacto en Tierra'}).first().click()
 const card=page.getByRole('region',{name:'Evidencia del candidato'})
 await card.getByText('Temperatura superficial · evidencia NASA',{exact:true}).click()
 await expect(card).toContainText('2025-08-04')
 const planetary=card.getByRole('region',{name:'Evidencia entre cuerpos'})
 await expect(planetary).toContainText('pNb')
 await expect(planetary).toContainText('LRO Diviner')
 await expect(planetary.getByText(/Diferencia observada Tierra − Luna/).first()).toBeVisible()
 await expect(card).toContainText('P10 / mediana / P90')
 await expect(card).toContainText('no aportan puntos al ranking')
})
