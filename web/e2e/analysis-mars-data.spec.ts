import {test,expect} from '@playwright/test'
 test('ventana exploratoria de Marte llega al comparador sin cambiar de destino',async({page})=>{
 test.slow();await page.route('https://**/*',route=>route.abort());await page.goto('/#personalizado')
 const dialog=page.locator('dialog[open]')
 await dialog.getByLabel('1 · Destino de misión').selectOption('mars-2')
 await dialog.getByLabel('2 · Cobertura de búsqueda').selectOption('pilot')
 await dialog.getByRole('button',{name:'Buscar análogos topográficos',exact:true}).click()
 await expect(dialog.getByRole('region',{name:'Resultados científicos'})).toBeVisible({timeout:60000})
 await dialog.getByRole('button',{name:'Ver recorte exacto en Tierra'}).first().click()
 const card=page.getByRole('region',{name:'Evidencia del candidato'})
 await expect(card).toContainText('Jezero')
 await card.getByRole('button',{name:'Comparar relieve 3D',exact:true}).click()
 const cmp=page.getByRole('dialog',{name:'Comparador de relieve planetario y terrestre'})
 await expect(cmp).toBeVisible()
 await expect(cmp.locator('canvas')).toHaveCount(2)
 await expect(cmp).toContainText('Jezero')
 await expect(cmp.getByLabel('Exageración vertical')).toBeVisible()
 await cmp.getByRole('button',{name:/Cerrar/}).click()
 await page.getByRole('navigation',{name:'Cuerpo visualizado'}).getByRole('button',{name:'Luna',exact:true}).click()
 const settings=page.getByRole('complementary',{name:'Misión y análisis'})
 await settings.getByRole('button',{name:'Ocultar panel'}).click()
 await expect(settings).toBeHidden()
 await page.getByRole('button',{name:'Mostrar panel de Luna'}).click()
 await expect(settings).toBeVisible()
 await page.getByRole('button',{name:/Ficha de la Luna/}).click()
 const lunarSheet=page.getByRole('complementary',{name:'Ficha de la Luna'})
 await expect(lunarSheet).toBeVisible()
 await lunarSheet.getByRole('button',{name:'Minimizar'}).click()
 await expect(lunarSheet).toBeHidden()
 await page.getByRole('navigation',{name:'Cuerpo visualizado'}).getByRole('button',{name:'Marte',exact:true}).click()
 await page.getByRole('button',{name:/Ficha de Marte/}).click()
 await expect(page.getByRole('complementary',{name:'Ficha de Marte'}).getByRole('region',{name:'Candidatos de la ejecución'})).toBeVisible()
 await page.getByRole('navigation',{name:'Cuerpo visualizado'}).getByRole('button',{name:'Tierra',exact:true}).click()
 await expect(card).toContainText('Jezero')
})
